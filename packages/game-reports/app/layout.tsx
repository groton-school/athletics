import { SignIn } from '@/components/Auth/SignIn';
import { User } from '@/components/Auth/User';
import { Bootstrap } from '@/components/Bootstrap';
import { auth } from '@/lib/auth';
import type { Metadata } from 'next';
import { Suspense } from 'react';
import { Container } from 'react-bootstrap';

import './globals.css';

export const metadata: Metadata = {
  title: 'Game Reports',
  description: 'Generated by create next app'
};

type Properties = LayoutProps<'/'>;

export default async function RootLayout(props: Properties) {
  return (
    <html lang="en">
      <body>
        <Container className="mt-3 mb-3 position-relative">
          <Suspense>
            <Avatar />
          </Suspense>
          <Suspense>
            <AuthenticatedContent {...props} />
          </Suspense>
        </Container>
        <Bootstrap />
      </body>
    </html>
  );
}

async function Avatar() {
  const session = await auth();
  if (session?.user) {
    return (
      <h6 className="position-absolute top-0 end-0 mt-1 me-3">
        <User />
      </h6>
    );
  }
  return <></>;
}

async function AuthenticatedContent({ children }: Properties) {
  const session = await auth();
  return <>{session?.user ? children : <SignIn />}</>;
}
