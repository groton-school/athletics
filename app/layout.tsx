import { SignIn } from '@/components/Auth/SignIn';
import { Bootstrap } from '@/components/Bootstrap';
import { auth } from '@/lib/auth';
import type { Metadata } from 'next';
import { Suspense } from 'react';
import { Container } from 'react-bootstrap';

import './globals.css';

export const metadata: Metadata = {
  title: 'Game Reports',
  description: 'Generated by create next app'
};

type Properties = LayoutProps<'/'>;

export default async function RootLayout(props: Properties) {
  return (
    <html lang="en">
      <body>
        <Container>
          <Suspense>
            <AuthenticatedContent {...props} />
          </Suspense>
        </Container>
        <Bootstrap />
      </body>
    </html>
  );
}

async function AuthenticatedContent({ children }: Properties) {
  const session = await auth();
  return <>{session?.user ? children : <SignIn />}</>;
}
